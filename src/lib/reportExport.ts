/**
 * Professional exports for the Reports pages: Excel (.xlsx), CSV and PDF from one description.
 * Every view builds an ExportDoc (title, period, filters, headline numbers, tables) and calls one of
 * exportXlsx / exportCsv / exportPdf. The heavy libraries are loaded only when someone exports.
 */
import { format } from 'date-fns';

export type ColumnType = 'text' | 'longtext' | 'number' | 'decimal' | 'percent' | 'date' | 'status';

export interface ExportColumn {
    key: string;
    header: string;
    type?: ColumnType;
    /** width in characters (Excel) and relative width (PDF) */
    width?: number;
}

export interface ExportTable {
    /** sheet name in Excel (max 31 chars) and section heading in the PDF */
    name: string;
    description?: string;
    columns: ExportColumn[];
    rows: Record<string, unknown>[];
}

export interface ExportDoc {
    title: string;
    /** usually the period, e.g. "1 Nov 2026 to 12 Nov 2026" */
    subtitle?: string;
    generatedBy: string;
    filters?: { label: string; value: string }[];
    summary?: { label: string; value: string | number }[];
    tables: ExportTable[];
    /** file name without extension */
    fileName: string;
}

const BRAND = 'EUSAI Team';
const now = () => new Date();
const stamp = (d = now()) => format(d, 'd MMM yyyy, h:mm a');

export function download(blob: Blob, name: string) {
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = name;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/** "2026-11-12" or Date -> Date at that calendar day (UTC midnight, so Excel never shifts it). */
function toDay(value: unknown): Date | null {
    if (value instanceof Date) return new Date(Date.UTC(value.getFullYear(), value.getMonth(), value.getDate()));
    if (typeof value === 'string') {
        const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(value);
        if (m) return new Date(Date.UTC(+m[1], +m[2] - 1, +m[3]));
        const d = new Date(value);
        if (!isNaN(d.getTime())) return new Date(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()));
    }
    return null;
}

const asNumber = (v: unknown) => (v === null || v === undefined || v === '' ? null : Number(v));
const fileSafe = (s: string) => s.replace(/[^\w\- ]+/g, '').trim().replace(/\s+/g, '-');

/** Text for CSV/PDF cells, by column type. */
function display(value: unknown, type: ColumnType = 'text', forPdf = false): string {
    if (value === null || value === undefined || value === '') return forPdf ? '–' : '';
    switch (type) {
        case 'date': { const d = toDay(value); return d ? (forPdf ? format(new Date(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate()), 'd MMM yyyy') : d.toISOString().slice(0, 10)) : String(value); }
        case 'percent': return forPdf ? `${Math.round(Number(value))}%` : String(Math.round(Number(value)));
        case 'decimal': return String(Math.round(Number(value) * 10) / 10);
        case 'number': return String(Number(value));
        default: return String(value);
    }
}

/* ------------------------------------------------------------------ Excel */

export async function exportXlsx(doc: ExportDoc) {
    const ExcelJS = (await import('exceljs')).default;
    const wb = new ExcelJS.Workbook();
    wb.creator = doc.generatedBy;
    wb.created = now();
    wb.title = doc.title;

    const HEADER_FILL = { type: 'pattern' as const, pattern: 'solid' as const, fgColor: { argb: 'FF111827' } };
    const thin = { style: 'thin' as const, color: { argb: 'FFE5E7EB' } };

    // Summary sheet
    const s = wb.addWorksheet('Summary', { views: [{ showGridLines: false }] });
    s.columns = [{ width: 30 }, { width: 48 }];
    s.addRow([BRAND]).font = { size: 10, color: { argb: 'FF6B7280' }, bold: true };
    s.addRow([doc.title]).font = { size: 18, bold: true };
    if (doc.subtitle) s.addRow([doc.subtitle]).font = { size: 12, color: { argb: 'FF374151' } };
    s.addRow([]);
    const meta: [string, string][] = [['Generated by', doc.generatedBy], ['Generated on', stamp()], ...(doc.filters || []).map(f => [f.label, f.value] as [string, string])];
    for (const [k, v] of meta) {
        const r = s.addRow([k, v]);
        r.getCell(1).font = { color: { argb: 'FF6B7280' } };
    }
    if (doc.summary?.length) {
        s.addRow([]);
        const h = s.addRow(['Metric', 'Value']);
        h.eachCell(c => { c.font = { bold: true, color: { argb: 'FFFFFFFF' } }; c.fill = HEADER_FILL; });
        for (const m of doc.summary) {
            const r = s.addRow([m.label, m.value]);
            r.eachCell(c => { c.border = { bottom: thin }; });
            r.getCell(2).alignment = { horizontal: 'left' };
        }
    }

    // One sheet per table
    const used = new Set<string>(['Summary']);
    for (const t of doc.tables) {
        let name = t.name.replace(/[\\/?*[\]:]/g, ' ').slice(0, 31);
        for (let i = 2; used.has(name); i++) name = `${t.name.slice(0, 28)} ${i}`;
        used.add(name);

        const ws = wb.addWorksheet(name, { views: [{ state: 'frozen', ySplit: 1 }] });
        ws.columns = t.columns.map(c => ({
            header: c.header,
            key: c.key,
            width: c.width ?? (c.type === 'longtext' ? 50 : c.type === 'date' ? 13 : c.type === 'text' ? 22 : 12),
        }));
        const header = ws.getRow(1);
        header.height = 22;
        header.eachCell(c => {
            c.font = { bold: true, color: { argb: 'FFFFFFFF' } };
            c.fill = HEADER_FILL;
            c.alignment = { vertical: 'middle', wrapText: true };
        });

        for (const row of t.rows) {
            const values: Record<string, unknown> = {};
            for (const c of t.columns) {
                const v = row[c.key];
                if (c.type === 'date') values[c.key] = toDay(v);
                else if (c.type === 'number' || c.type === 'decimal' || c.type === 'percent') values[c.key] = asNumber(v);
                else values[c.key] = v === null || v === undefined ? '' : String(v);
            }
            const r = ws.addRow(values);
            r.alignment = { vertical: 'top' };
            t.columns.forEach((c, i) => {
                const cell = r.getCell(i + 1);
                cell.border = { bottom: thin };
                if (c.type === 'date') cell.numFmt = 'dd mmm yyyy';
                if (c.type === 'percent') cell.numFmt = '0"%"';
                if (c.type === 'decimal') cell.numFmt = '0.0';
                if (c.type === 'longtext') cell.alignment = { wrapText: true, vertical: 'top' };
                if (c.type === 'number' || c.type === 'decimal' || c.type === 'percent') cell.alignment = { horizontal: 'right', vertical: 'top' };
            });
        }
        if (t.rows.length) ws.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: t.columns.length } };
    }

    const buffer = await wb.xlsx.writeBuffer();
    download(new Blob([buffer], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' }), `${fileSafe(doc.fileName)}.xlsx`);
}

/* -------------------------------------------------------------------- CSV */

export function exportCsv(doc: ExportDoc, tableIndex = 0) {
    const t = doc.tables[tableIndex];
    if (!t) return;
    const esc = (s: string) => (/[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);
    const lines = [
        t.columns.map(c => esc(c.header)).join(','),
        ...t.rows.map(r => t.columns.map(c => esc(display(r[c.key], c.type))).join(',')),
    ];
    // BOM so Excel reads UTF-8 (names, ₹, bullets) correctly; CRLF for Windows tools
    download(new Blob(['﻿' + lines.join('\r\n')], { type: 'text/csv;charset=utf-8' }), `${fileSafe(doc.fileName)}.csv`);
}

/* -------------------------------------------------------------------- PDF */

/** The built-in PDF font only covers Western characters; swap the common others for readable equivalents. */
function pdfText(s: string) {
    return s
        .replace(/₹/g, 'Rs. ')
        .replace(/[–—]/g, '-')
        .replace(/[•●▪]/g, '-')
        .replace(/[^\u0009\u000A\u000D -~ -ÿ‘’“”…]/g, '');
}

export async function exportPdf(doc: ExportDoc) {
    const { default: jsPDF } = await import('jspdf');
    const { default: autoTable } = await import('jspdf-autotable');

    const pdf = new jsPDF({ orientation: 'landscape', unit: 'pt', format: 'a4', compress: true });
    const W = pdf.internal.pageSize.getWidth();
    const H = pdf.internal.pageSize.getHeight();
    const M = 36;
    const INK: [number, number, number] = [17, 24, 39];
    const MUTED: [number, number, number] = [107, 114, 128];
    const generated = stamp();

    // title block
    pdf.setFillColor(...INK);
    pdf.rect(0, 0, W, 6, 'F');
    pdf.setFont('helvetica', 'bold'); pdf.setFontSize(9); pdf.setTextColor(...MUTED);
    pdf.text(BRAND.toUpperCase(), M, 30);
    pdf.setFontSize(20); pdf.setTextColor(...INK);
    pdf.text(pdfText(doc.title), M, 54);
    pdf.setFont('helvetica', 'normal'); pdf.setFontSize(11); pdf.setTextColor(55, 65, 81);
    if (doc.subtitle) pdf.text(pdfText(doc.subtitle), M, 72);
    pdf.setFontSize(9); pdf.setTextColor(...MUTED);
    pdf.text(pdfText(`Generated ${generated}`), W - M, 30, { align: 'right' });
    pdf.text(pdfText(`by ${doc.generatedBy}`), W - M, 43, { align: 'right' });

    let y = doc.subtitle ? 88 : 74;
    if (doc.filters?.length) {
        pdf.setFontSize(9); pdf.setTextColor(...MUTED);
        const line = doc.filters.map(f => `${f.label}: ${f.value}`).join('   |   ');
        const wrapped = pdf.splitTextToSize(pdfText(line), W - 2 * M);
        pdf.text(wrapped, M, y);
        y += wrapped.length * 11 + 6;
    }

    // headline numbers
    if (doc.summary?.length) {
        const items = doc.summary.slice(0, 6);
        const gap = 10;
        const boxW = (W - 2 * M - gap * (items.length - 1)) / items.length;
        items.forEach((m, i) => {
            const x = M + i * (boxW + gap);
            pdf.setDrawColor(229, 231, 235); pdf.setFillColor(249, 250, 251);
            pdf.roundedRect(x, y, boxW, 50, 4, 4, 'FD');
            pdf.setFont('helvetica', 'bold'); pdf.setFontSize(16); pdf.setTextColor(...INK);
            pdf.text(pdfText(String(m.value)), x + 10, y + 24);
            pdf.setFont('helvetica', 'normal'); pdf.setFontSize(8); pdf.setTextColor(...MUTED);
            pdf.text(pdfText(m.label), x + 10, y + 39, { maxWidth: boxW - 20 });
        });
        y += 66;
    }

    // tables
    for (const t of doc.tables) {
        if (y > H - 120) { pdf.addPage(); y = M; }
        pdf.setFont('helvetica', 'bold'); pdf.setFontSize(12); pdf.setTextColor(...INK);
        pdf.text(pdfText(t.name), M, y + 4);
        y += 10;
        if (t.description) {
            pdf.setFont('helvetica', 'normal'); pdf.setFontSize(9); pdf.setTextColor(...MUTED);
            pdf.text(pdfText(t.description), M, y + 8);
            y += 12;
        }

        // Column widths: every column fits its header and a full date on one line; the rest of the
        // page goes to columns by weight, and long-text columns give way first if space runs out.
        const usable = W - 2 * M;
        const weight = (c: ExportColumn) => c.width ?? (c.type === 'longtext' ? 50 : 14);
        pdf.setFont('helvetica', 'bold'); pdf.setFontSize(8);
        const minW = t.columns.map(c => {
            const header = Math.max(...pdfText(c.header).split(' ').map(w => pdf.getTextWidth(w))) + 14;
            const content = c.type === 'date' ? pdf.getTextWidth('30 Sep 2026') + 14 : c.type === 'longtext' ? 70 : c.type === 'status' ? 18 : 30;
            return Math.max(header, content);
        });
        const totalWeight = t.columns.reduce((s, c) => s + weight(c), 0);
        let widths = t.columns.map((c, i) => Math.max(minW[i], (usable * weight(c)) / totalWeight));
        const over = widths.reduce((s, w) => s + w, 0) - usable;
        if (over > 0) {
            const flexible = t.columns.map((c, i) => (c.type === 'longtext' || c.type === 'text' ? widths[i] - minW[i] : 0));
            const room = flexible.reduce((s, f) => s + f, 0);
            if (room > 0) widths = widths.map((w, i) => w - (flexible[i] / room) * Math.min(over, room));
        }
        const finalWidths = widths.map(w => (w * usable) / widths.reduce((s, x) => s + x, 0));
        autoTable(pdf, {
            startY: y + 6,
            margin: { left: M, right: M, bottom: 40 },
            head: [t.columns.map(c => pdfText(c.header))],
            body: t.rows.length
                ? t.rows.map(r => t.columns.map(c => pdfText(display(r[c.key], c.type, true))))
                : [[{ content: 'No records for this period.', colSpan: t.columns.length, styles: { halign: 'center', textColor: MUTED } }]],
            theme: 'plain',
            rowPageBreak: 'avoid', // never split one report across two pages
            styles: { font: 'helvetica', fontSize: 8, cellPadding: { top: 5, bottom: 5, left: 6, right: 6 }, textColor: [31, 41, 55], overflow: 'linebreak', valign: 'top', lineColor: [229, 231, 235], lineWidth: { bottom: 0.5 } },
            headStyles: { fillColor: INK, textColor: [255, 255, 255], fontStyle: 'bold', fontSize: 8, valign: 'middle' },
            alternateRowStyles: { fillColor: [249, 250, 251] },
            columnStyles: Object.fromEntries(t.columns.map((c, i) => [i, {
                cellWidth: finalWidths[i],
                halign: c.type === 'number' || c.type === 'decimal' || c.type === 'percent' ? 'right' : c.type === 'status' ? 'center' : 'left',
            }])),
        });
        y = (pdf as any).lastAutoTable.finalY + 24;
    }

    // footer on every page
    const pages = pdf.getNumberOfPages();
    for (let i = 1; i <= pages; i++) {
        pdf.setPage(i);
        pdf.setDrawColor(229, 231, 235);
        pdf.line(M, H - 28, W - M, H - 28);
        pdf.setFont('helvetica', 'normal'); pdf.setFontSize(8); pdf.setTextColor(...MUTED);
        pdf.text(pdfText(`${BRAND}  |  ${doc.title}  |  Confidential, for internal use`), M, H - 16);
        pdf.text(`Page ${i} of ${pages}`, W - M, H - 16, { align: 'right' });
    }

    download(pdf.output('blob'), `${fileSafe(doc.fileName)}.pdf`);
}
